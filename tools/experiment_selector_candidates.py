#!/usr/bin/env python3
"""Prototype the ROM selector candidate phases without changing the engine.

This models only the candidate selection/order visible at $A2CF-$A3B0 and
$936C-$944D.  Candidate execution, bounds and recursive return handling remain
in the ROM/engine.  The prototype is intentionally trace-oriented: every
candidate records its selector phase and the ROM try-move entry it would use.
"""
from __future__ import annotations

import argparse
from dataclasses import dataclass, field
import json
from pathlib import Path
import sys

_REPO_ROOT = Path(__file__).resolve().parents[1]
if str(_REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(_REPO_ROOT))

from pyqiwang import BLACK, RED, Board
from pyqiwang._board import generate_piece_moves, PIECE_TYPES

Move = tuple[int, int]

# ROM geometry tables used by $8DC7/$903B.  The destination mask is stored at
# $8160+target; the per-piece delta bit is stored at $81CA/$81DA.  A candidate
# survives only when both bitwise tests are zero.  Values not listed in the
# delta table behave as $FF and reject every piece.
_ROM_SQUARE_MASKS = bytes.fromhex(
    "7f 7f 7b 7f 77 77 f7 b7 f7 f7 ff ff "
    "7f 7f 7f 7f 7f f7 f7 f7 f7 f7 ff ff "
    "7b 7f 7f 7f 73 37 f7 f7 f7 b7 ff ff "
    "7c 7e 7c 7f 7f f7 f7 c7 e7 c7 ff ff "
    "7e 7c 7a 7f 77 77 f7 a7 c7 e7 ff ff "
    "7c 7e 7c 7f 7f f7 f7 c7 e7 c7 ff ff "
    "7b 7f 7f 7f 73 37 f7 f7 f7 b7 ff ff "
    "7f 7f 7f 7f 7f f7 f7 f7 f7 f7 ff ff "
    "7f 7f 7b 7f 77 77 f7 b7 f7 f7"
)
_ROM_RED_SQUARE_BITS = (1, 0, 0, 0, 0, 0, 0, 2, 2, 4, 4, 8, 8, 8, 8, 8)
_ROM_BLACK_SQUARE_BITS = (
    16, 0, 0, 0, 0, 0, 0, 32, 32, 64, 64, 128, 128, 128, 128, 128,
)
_ROM_RED_DELTA_BITS = (1, 2, 2, 4, 4, 8, 8, 16, 16, 32, 32, 64, 64, 64, 64, 64)
_ROM_BLACK_DELTA_BITS = (
    1, 2, 2, 4, 4, 8, 8, 16, 16, 32, 32, 128, 128, 128, 128, 128,
)
_ROM_DELTA_RULES = {
    -96: (249, -12), -84: (249, -12), -72: (249, -12),
    -60: (249, -12), -48: (249, -12), -36: (249, -12),
    -26: (223, -13), -25: (247, -12), -24: (249, -12),
    -23: (247, -12), -22: (223, -11), -14: (247, -1),
    -13: (239, -13), -12: (60, -12), -11: (239, -11),
    -10: (247, 1), -9: (248, -1), -8: (248, -1),
    -7: (248, -1), -6: (248, -1), -5: (248, -1),
    -4: (249, -1), -3: (249, -1), -2: (249, -1),
    -1: (124, -1), 1: (188, 1), 2: (249, 1), 3: (249, 1),
    4: (249, 1), 5: (248, 1), 6: (248, 1), 7: (248, 1),
    8: (248, 1), 9: (248, 1), 10: (247, -1), 11: (239, 11),
    12: (60, 12), 13: (239, 13), 14: (247, 1), 22: (223, 11),
    23: (247, 12), 24: (249, 12), 25: (247, 12),
    26: (223, 13), 36: (249, 12), 48: (249, 12),
    60: (249, 12), 72: (249, 12), 84: (249, 12), 96: (249, 12),
}


@dataclass(frozen=True)
class Candidate:
    move: Move
    phase: str
    selector: int
    rom_entry: str


@dataclass
class SelectorFrame:
    """Python representation of one ROM $C6-indexed selector frame."""

    level: int
    # Side that owns the candidate moves generated by this selector node.
    side: int
    bound_raw: int = 0
    previous_bound_raw: int = 0
    best_raw: int = 0
    child_raw: int = 0
    selector: int = 0xFF
    history_move: Move | None = None
    previous_history_move: Move | None = None
    current_move: Move | None = None
    saved_target: int | None = None
    cf: int = 0
    candidates: list[Candidate] = field(default_factory=list)


class SelectorCandidatePrototype:
    """Translate the selector-controlled candidate phases from ROM traces."""

    def __init__(self, board: Board, frame: SelectorFrame,
                 legal_moves: set[Move] | None = None):
        self.board = board
        self.frame = frame
        self.legal_moves = legal_moves

    def _valid_piece_move(self, move: Move, side: int) -> bool:
        if self.legal_moves is not None:
            return move in self.legal_moves
        frm, to = move
        if not (self.board.is_valid_pos(frm) and self.board.is_valid_pos(to)):
            return False
        try:
            idx = self.board.pieces[side].index(frm)
        except ValueError:
            return False
        return move in generate_piece_moves(
            self.board, side, frm, PIECE_TYPES[idx]
        )


    def _append(self, move: Move, phase: str, selector: int,
                entry: str) -> None:
        self.frame.candidates.append(Candidate(move, phase, selector, entry))

    def _already_generated(self, move: Move) -> bool:
        return any(candidate.move == move for candidate in self.frame.candidates)

    def _target_responses(self) -> None:
        """ROM $A2CF/$936C: every opposing piece that reaches saved target."""
        target = self.frame.saved_target
        if target is None:
            return
        candidate_side = self.frame.side
        entry = "$B607" if candidate_side == BLACK else "$B27F"
        for idx, frm in enumerate(self.board.pieces[candidate_side]):
            if frm < 0:
                continue
            move = (frm, target)
            if self._valid_piece_move(move, candidate_side):
                self._append(move, "saved-target-response", 0xFF, entry)

    def _history_candidate(self, move: Move | None, phase: str,
                           selector: int) -> None:
        if move is None or self.frame.level >= 8:
            return
        frm, to = move
        candidate_side = self.frame.side
        if frm < 0 or to < 0 or to == self.frame.saved_target:
            return
        # $A2F9/$93A6 and their secondary-history twins accept an empty target
        # or a target not occupied by the moving side.  $CF must be nonnegative
        # for the empty-target path.
        if not self._valid_piece_move(move, candidate_side):
            return
        target_side = self.board.get_side(to)
        if target_side == candidate_side:
            return
        if target_side is None and self.frame.cf >= 0x80:
            return
        entry = "$B583" if candidate_side == BLACK else "$B1FB"
        self._append(move, phase, selector, entry)

    def _rom_table_candidate(self, source_idx: int, frm: int,
                             to: int) -> bool:
        """Exact $8DC7/$903B attack test for one occupied target.

        This is deliberately not ordinary Xiangqi move generation.  The ROM
        first applies target-square and signed-delta masks, then performs only
        the blocker scan required by the source piece index.  Rooks need one
        occupied square on the ray (the target); cannons need two.  Knights and
        elephants check their one intermediate square.  Other indexed pieces
        have no blocker scan in these routines.
        """
        if not (0 <= to < len(_ROM_SQUARE_MASKS)):
            return False
        side = self.frame.side
        square_bits = (
            _ROM_RED_SQUARE_BITS if side == RED else _ROM_BLACK_SQUARE_BITS
        )
        if square_bits[source_idx] & _ROM_SQUARE_MASKS[to]:
            return False

        rule = _ROM_DELTA_RULES.get(to - frm)
        if rule is None:
            return False
        delta_mask, step = rule
        delta_bits = (
            _ROM_RED_DELTA_BITS if side == RED else _ROM_BLACK_DELTA_BITS
        )
        if delta_bits[source_idx] & delta_mask:
            return False

        # Source indices 1/2 are rooks and 3/4 are cannons in the ROM order.
        # The 6502 loops stop at occupied squares rather than board edges; the
        # mask tables guarantee that an accepted delta supplies a nonzero step.
        if source_idx in (1, 2, 3, 4):
            occupied_needed = 2 if source_idx in (3, 4) else 1
            pos = frm
            for _ in range(occupied_needed):
                while True:
                    pos += step
                    # The ROM's 12-stride board keeps the two padding ranks
                    # occupied by sentinels.  Python Board.cells leaves those
                    # invalid positions empty, so testing only the numeric
                    # range lets rook/cannon rays wrap across files.
                    if not self.board.is_valid_pos(pos):
                        return False
                    if self.board.cells[pos] != 0:
                        break
            return pos == to

        # Knight indices 5/6 and elephant indices 9/10 use the ROM step table
        # as their leg/eye square.  The advisor, king and pawn entries need only
        # the two mask tests above.
        if source_idx in (5, 6, 9, 10):
            leg = frm + step
            return 0 <= leg < len(self.board.cells) and self.board.cells[leg] == 0
        return True

    def _table_driven_candidates(self, target_indices: range) -> None:
        """ROM $903B/$8DC7 selective attacks against occupied targets.

        Each unrolled ROM routine tests source indices 15 down to 0 and passes
        every accepted pair through the history/dedup gate ($B5E3/$B25B).
        The caller controls the target slice because $A363/$9400 always visit
        king and rooks (0..2), but visit targets 3..15 only for the CF>=FE path.
        """
        side = self.frame.side
        entry = "$B5E3" if side == BLACK else "$B25B"
        for target_idx in target_indices:
            to = self.board.pieces[1 - side][target_idx]
            if to < 0:
                continue
            for source_idx in range(15, -1, -1):
                frm = self.board.pieces[side][source_idx]
                if frm < 0:
                    continue
                move = (frm, to)
                if (not self._already_generated(move) and
                        self._rom_table_candidate(source_idx, frm, to)):
                    self._append(move, "table-driven", 1, entry)

    def _directed_reply(self) -> None:
        """ROM $A385/$9422: move the prior origin to a major-piece square.

        The loop checks only piece indices 3..15 and excludes the saved target.
        The exact try-move entry is side-symmetric ($B5E3/$B25B).
        """
        if self.frame.cf >= 0xFE or self.frame.selector >= 0x80:
            return
        if self.frame.current_move is None or self.frame.saved_target is None:
            return
        frm = self.frame.current_move[0]
        if frm == self.frame.saved_target:
            return
        candidate_side = self.frame.side
        entry = "$B5E3" if candidate_side == BLACK else "$B25B"
        for idx in range(3, 16):
            to = self.board.pieces[candidate_side][idx]
            if to < 0 or to == self.frame.saved_target:
                continue
            move = (frm, to)
            if self._valid_piece_move(move, candidate_side):
                self._append(move, "directed-reply", 2, entry)

    def generate(self) -> list[Candidate]:
        self.frame.candidates.clear()
        self.frame.selector = 0xFF
        self._target_responses()
        self._history_candidate(
            self.frame.history_move, "primary-history", 0xFF
        )
        self.frame.selector = 0
        self._history_candidate(
            self.frame.previous_history_move, "secondary-history", 0
        )
        self.frame.selector = 1
        self._table_driven_candidates(range(3))
        if self.frame.cf >= 0xFE:
            self._table_driven_candidates(range(3, 16))
        self.frame.selector = 2
        self._directed_reply()
        return list(self.frame.candidates)


def board_from_record(record: dict) -> Board:
    board = Board()
    board.pieces[RED] = list(record["red"])
    board.pieces[BLACK] = list(record["black"])
    board.side_to_move = int(record["side"])
    board.move_history = []
    board._init_board()
    return board


def load_case(path: Path, case_id: str) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    for case in data["cases"]:
        if case["id"] == case_id:
            return case
    raise KeyError(case_id)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--fixture",
        type=Path,
        default=_REPO_ROOT / "tests" / "fixtures" /
        "rom_depth1_independent.json",
    )
    parser.add_argument("--case", default="random-015")
    parser.add_argument(
        "--side", choices=("red", "black"), default="black",
        help="side that owns candidates generated by this selector node",
    )
    parser.add_argument("--level", type=int, default=3)
    parser.add_argument("--saved-target", type=int, required=True)
    parser.add_argument("--current", nargs=2, type=int, metavar=("FROM", "TO"))
    parser.add_argument(
        "--applied-move", action="append", nargs=2, type=int,
        metavar=("FROM", "TO"), default=[],
        help="apply a move to the fixture before generating this selector frame",
    )
    parser.add_argument("--history", nargs=2, type=int, metavar=("FROM", "TO"))
    parser.add_argument(
        "--previous-history", nargs=2, type=int, metavar=("FROM", "TO")
    )
    parser.add_argument("--cf", type=lambda value: int(value, 0), default=0)
    args = parser.parse_args()

    case = load_case(args.fixture, args.case)
    board = board_from_record(case["board"])
    for move in args.applied_move:
        board.make_move(*move)
    frame = SelectorFrame(
        level=args.level,
        side=RED if args.side == "red" else BLACK,
        history_move=tuple(args.history) if args.history else None,
        previous_history_move=(
            tuple(args.previous_history) if args.previous_history else None
        ),
        current_move=tuple(args.current) if args.current else None,
        saved_target=args.saved_target,
        cf=args.cf,
    )
    candidates = SelectorCandidatePrototype(board, frame).generate()
    print(json.dumps({
        "case": args.case,
        "frame": {
            "level": frame.level,
            "side": frame.side,
            "saved_target": frame.saved_target,
            "current_move": frame.current_move,
            "history_move": frame.history_move,
            "previous_history_move": frame.previous_history_move,
            "applied_moves": args.applied_move,
            "selector_after": frame.selector,
        },
        "candidates": [
            {
                "move": candidate.move,
                "phase": candidate.phase,
                "selector": candidate.selector,
                "rom_entry": candidate.rom_entry,
            }
            for candidate in candidates
        ],
    }, ensure_ascii=False, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
